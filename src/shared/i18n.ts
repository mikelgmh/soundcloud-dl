export const DICTS: Record<Lang, Dict> = { es, en };

export interface Vars {
  [key: string]: string | number;
}

/** Traduce una clave a la lengua dada. Sustituye {var} por los valores. */
export function t(lang: Lang, key: string, vars?: Vars): string {
  const dict = DICTS[lang] ?? en;
  let out = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

/** Normaliza cualquier valor a una lengua soportada (fallback en). */
export function normalizeLang(value: unknown): Lang {
  return value === "es" || value === "en" ? value : DEFAULT_LANG;
}

/** Detecta el idioma del sistema desde el entorno (webview o Bun). */
export function detectSystemLang(): Lang {
  // En la webview, navigator.language refleja el idioma del SO.
  if (typeof navigator !== "undefined" && navigator.language) {
    return normalizeLang(navigator.language.split("-")[0]?.toLowerCase());
  }
  // En Bun: variables de entorno del sistema.
  const env = (
    process.env.LC_ALL ||
    process.env.LANG ||
    process.env.LC_MESSAGES ||
    ""
  ).toLowerCase();
  return normalizeLang(env.split(/[-_.]/)[0]);
}

/** Resuelve la lengua efectiva: config guardada > idioma del sistema > en. */
export function resolveLang(configured?: string | null): Lang {
  return normalizeLang(configured ?? detectSystemLang());
}
